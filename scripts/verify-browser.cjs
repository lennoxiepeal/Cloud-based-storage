const { chromium, expect } = require('../.tools/local-services/node_modules/@playwright/test');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', dialog => dialog.accept());
  const login = async (p, username, password) => {
    await p.goto('http://localhost:8080/login');
    await p.getByPlaceholder('Enter your username').fill(username);
    await p.getByPlaceholder('Enter your password').fill(password);
    await p.getByRole('button', {name:'Sign In',exact:true}).click();
    await expect(p.getByRole('button',{name:'Logout'})).toBeVisible();
  };
  await login(page, 'demo', 'demo123');
  const roots = await (await context.request.get('http://localhost:8080/api/folders/list')).json();
  for (const folder of roots.folders.filter(f => /^Demo workspace( \d+)?$/.test(f.name))) {
    await context.request.delete(`http://localhost:8080/api/folders/${folder.id}?deleteContents=true`);
  }
  await page.reload();
  await page.screenshot({path:'logs/dashboard-before.png',fullPage:true});
  await page.getByRole('button',{name:'New Folder'}).click();
  const folderName = 'Demo workspace ' + Date.now();
  await page.getByPlaceholder('Enter folder name').fill(folderName);
  await page.getByRole('button',{name:'Create',exact:true}).click();
  await page.getByText(folderName,{exact:true}).click();
  await expect(page.locator('.breadcrumb')).toContainText(folderName);
  await page.getByRole('button',{name:'New Folder'}).click();
  await page.getByPlaceholder('Enter folder name').fill('Reports');
  await page.getByRole('button',{name:'Create',exact:true}).click();
  await expect(page.locator('.folder-name')).toHaveText(['Reports']);
  await page.locator('input[type=file]').setInputFiles(['project-report.txt','storage-results.csv','architecture.svg'].map(f=>path.resolve(__dirname,'../demo-files',f)));
  await page.getByRole('button',{name:'Upload 3 File(s)',exact:true}).click();
  await expect(page.locator('.file-table tbody tr')).toHaveCount(3,{timeout:30000});
  await page.screenshot({path:'logs/demo-workspace.png',fullPage:true});
  console.log('PASS: browser login, nested folder navigation, upload with S3 CORS, and file listing');
  const row = page.locator('tr').filter({hasText:'project-report.txt'});
  await row.getByTitle('Rename',{exact:true}).click();
  await page.locator('.modal input').fill('final-report.txt');
  await page.locator('.modal').getByRole('button',{name:'Rename',exact:true}).click();
  const renamed = page.locator('tr').filter({hasText:'final-report.txt'});
  await renamed.getByTitle('Make Public',{exact:true}).click();
  const link = await page.locator('.modal input').inputValue();
  const anon = await browser.newContext();
  const shared = await anon.newPage();
  await shared.goto(link);
  await expect(shared.getByRole('heading',{name:'final-report.txt'})).toBeVisible();
  await shared.reload();
  await expect(shared.getByRole('button',{name:'Download File'})).toBeVisible();
  await shared.screenshot({path:'logs/public-share.png',fullPage:true});
  await page.locator('.modal-close').click();
  await page.reload();
  await page.getByText(folderName,{exact:true}).click();
  await expect(page.locator('tr').filter({hasText:'final-report.txt'})).toBeVisible();
  await page.locator('tr').filter({hasText:'final-report.txt'}).getByTitle('Make Private').click();
  await shared.reload();
  await expect(shared.getByText('File not found or link has been revoked')).toBeVisible();
  console.log('PASS: browser rename, public sharing in a separate session, page refresh, and revocation');
  await page.getByPlaceholder('Search files...').fill('final-report');
  await page.getByPlaceholder('Search files...').press('Enter');
  await expect(page.locator('.file-table tbody tr')).toHaveCount(1);
  await page.getByPlaceholder('Search files...').fill('');
  await page.getByPlaceholder('Search files...').press('Enter');
  await expect(page.locator('.file-table tbody tr')).toHaveCount(3);
  await page.getByPlaceholder('Search files...').fill('Reports');
  await page.getByPlaceholder('Search files...').press('Enter');
  await expect(page.locator('.folder-name')).toHaveText(['Reports']);
  await page.getByPlaceholder('Search files...').fill('');
  await page.getByPlaceholder('Search files...').press('Enter');
  await page.getByTitle('Advanced Search').click();
  await page.locator('.card').filter({has:page.getByRole('heading',{name:'Advanced Search Filters'})}).locator('select').selectOption('image');
  await page.getByRole('button',{name:'Search',exact:true}).click();
  await expect(page.locator('.file-table tbody tr')).toHaveCount(1);
  await page.getByRole('button',{name:'Clear Filters'}).click();
  await expect(page.locator('.file-table tbody tr')).toHaveCount(3);
  console.log('PASS: browser folder search, advanced type filtering, and clear filters');
  await page.getByRole('button',{name:'Logout'}).click();
  await login(page, 'admin', 'admin123');
  await expect(page.getByRole('heading',{name:'Admin Panel'})).toBeVisible();
  await expect(page.getByText('Total Users',{exact:true})).toBeVisible();
  await expect(page.locator('tr').filter({hasText:'demo'})).toBeVisible();
  const demoRow = page.locator('tr').filter({has:page.getByRole('cell',{name:'demo',exact:true})});
  await demoRow.getByRole('spinbutton').fill('2');
  await demoRow.getByRole('button',{name:'Update',exact:true}).click();
  await expect(demoRow.getByRole('spinbutton')).toHaveValue('2.00');
  await demoRow.getByRole('checkbox',{name:'Read',exact:true}).uncheck();
  await Promise.all([page.waitForEvent('dialog',{predicate:d=>d.message()==='Permissions updated'}), demoRow.getByRole('button',{name:'Save Permissions'}).click()]);
  await expect(demoRow.getByRole('checkbox',{name:'Read',exact:true})).not.toBeChecked();
  await demoRow.getByRole('checkbox',{name:'Read',exact:true}).check();
  await Promise.all([page.waitForEvent('dialog',{predicate:d=>d.message()==='Permissions updated'}), demoRow.getByRole('button',{name:'Save Permissions'}).click()]);
  await page.locator('.global-quota input').fill('1');
  await Promise.all([page.waitForEvent('dialog',{predicate:d=>d.message()==='All user quotas updated'}), page.getByRole('button',{name:'Apply to All'}).click()]);
  await expect(demoRow.getByRole('spinbutton')).toHaveValue('1.00');
  console.log('PASS: browser per-user/global quota updates and permission editing');
  await page.screenshot({path:'logs/admin-panel.png',fullPage:true});
  console.log('PASS: browser search/reset, logout, administrator login and statistics/users UI');
  expect(errors).toEqual([]);
  await browser.close();
  console.log('ALL BROWSER CHECKS PASSED');
})().catch(e=>{console.error(e);process.exit(1)});
